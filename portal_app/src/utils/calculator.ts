import { AssessmentInput, AssessmentResult } from '../types/protocol';

export function calculateRecoveryReadiness(input: AssessmentInput): AssessmentResult {
  const { daysPostOp, dressingStatus, painOrTension } = input;

  // Red flags detection
  if (dressingStatus === 'active_leak') {
    return {
      currentPhase: 1,
      showerSafety: 'consult_doctor_first',
      headlineAr: 'يُرجى مراجعة طبيب النساء والتوليد قبل الاستحمام المباشر',
      guidanceAr:
        'وجود إفرازات نشطة أو تسريب من الجرح يستدعي فحص الطبيب المعالج أولاً للتأكد من سلامة طبقات الالتئام. يمكنك غسل باقي الجسم بقطعة قماش ناعمة مبللة دون تعريض منطقة القيصرية لتيار الماء.',
      showerProtocolAr: [
        'تجنبي تسليط تيار ماء الدش المباشر على منطقة أسفل البطن.',
        'حافظي على جفاف الضمادة الحالية واطلبي استشارة طبيبك لتغييرها.',
        'بعد موافقة الطبيب، يمكنك استخدام درع الشاور العازل للاستحمام الآمن.'
      ],
      warningNoteAr: 'تنبيه سريري: لا تتركي الجرح رطباً أو مكشوفاً للماء إذا كان هناك نزيف أو سائل مصلي غير معتاد.',
      recommendedKitId: 'phase-1-shower-shields'
    };
  }

  // Phase 1: Days 1 to 21
  if (daysPostOp <= 21) {
    return {
      currentPhase: 1,
      showerSafety: 'safe_with_shield',
      headlineAr: 'مسموح بالاستحمام الكامل فوراً مع درع الشاور العازل للماء',
      guidanceAr:
        `أنتِ في اليوم ${daysPostOp} من التعافي. الجرح في مرحلة الحماية الحيوية الأولى. استخدام درع هيلينج تاتش العازل يمنع تسرب قطرات الماء والشامبو والصابون 100%، مما يتيح لك الاستمتاع بشاور منعش ودافئ دون أدنى خوف من التلوث.`,
      showerProtocolAr: [
        'جففي الجلد المحيط بالجرح بلطف بقطعة قطن نظيفة بطريقة الطبطبة.',
        'ثبتي درع الشاور العازل الطبي مقاس 25×10 سم واضغطي حوافه برفق.',
        'استحمي بحرية تامة بماء دافئ يريح عضلات ظهرك وبطنك.',
        'بعد الاستحمام، انزعي اللصقة من الأعلى للأسفل بنعومة وتخلصي منها.'
      ],
      recommendedKitId: 'complete-protocol-bundle'
    };
  }

  // Phase 2: Weeks 3 to 12 (Days 22 to 84)
  if (daysPostOp <= 84) {
    return {
      currentPhase: 2,
      showerSafety: 'mature_healing',
      headlineAr: 'الجرح مستقر للاستحمام العادي - الوقت الذهبي لشرائح السيليكون',
      guidanceAr:
        `أنتِ في الأسبوع ${Math.floor(daysPostOp / 7)} بعد القيصرية. الجرح مغلق سطحياً ومستعد للاستحمام المباشر اللطيف. هذه هي الفترة الحرجة التي يقرر فيها جسمك شكل الندبة؛ شرائح السيليكون الطبية تمنع تشكل الجدرة (Keloid) وتسطح الخط تماماً.`,
      showerProtocolAr: [
        'يمكنك الاستحمام بالماء الجاري مع تجنب فرك خط الندبة بالليفة مباشرة.',
        'جففي خط القيصرية تماماً قبل إعادة ارتداء شريحة السيليكون الطبية.',
        'ارتدي شريحة السيليكون لمدة 12-20 ساعة يومياً للحصول على أفضل تسطيح.',
        'اغسلي الشريحة كل 2-3 أيام بالماء الفاتر لتجديد التصاقها الطبيعي.'
      ],
      recommendedKitId: 'phase-2-silicone-sheets'
    };
  }

  // Phase 3: Beyond 12 weeks
  return {
    currentPhase: 3,
    showerSafety: 'mature_healing',
    headlineAr: 'مرحلة النضج وتفتيح التصبغات وتنعيم الندبة المتقدم',
    guidanceAr:
      'لقد تجاوزتِ المرحلة الأولى بنجاح. ألياف الكولاجين الآن في مرحلة إعادة الترتيب حتى تمام العام. استخدام جل السيليكون المركز مع السيراميد وفيتامين E مرتين يومياً يفتح اللون الداكن ويدمج الندبة مع لون بشرتك الطبيعي.',
    showerProtocolAr: [
      'استحمام طبيعي كامل وعناية يومية روتينية.',
      'تدليك خط الندبة لمدة دقيقة بعد الشاور بنقاط من جل السيراميد المركز.',
      'تجنبي تعريض منطقة الندبة للشمس المباشرة دون حماية لمنع الاسمرار.'
    ],
    recommendedKitId: 'phase-3-scar-gel'
  };
}
